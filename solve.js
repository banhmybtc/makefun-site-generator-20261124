/** The characters a backslash escapes, as a lookup by char code. */
const ESCAPABLE = new Uint8Array(128);
for (const c of '\\`*_[]()#+-.!>') ESCAPABLE[c.charCodeAt(0)] = 1;

/** The first index from `from` where `s` holds "**" outside a backslash escape, or -1. */
function findDoubleStar(s, from) {
  for (let j = from; j + 1 < s.length; j++) {
    const c = s.charCodeAt(j);
    if (c === 92 && j + 1 < s.length && ESCAPABLE[s.charCodeAt(j + 1)] === 1) {
      j++;
      continue;
    }
    if (c === 42 && s.charCodeAt(j + 1) === 42) return j;
  }
  return -1;
}

/** The first index from `from` where `s` holds "]" outside a backslash escape, or -1. */
function findUnescapedBracket(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s.charCodeAt(j);
    if (c === 92 && j + 1 < s.length && ESCAPABLE[s.charCodeAt(j + 1)] === 1) {
      j++;
      continue;
    }
    if (c === 93) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s.charCodeAt(j);
    if (c === 92 && j + 1 < s.length && ESCAPABLE[s.charCodeAt(j + 1)] === 1) {
      j++;
      continue;
    }
    if (c !== 42) continue;
    if (s.charCodeAt(j + 1) === 42) {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/** The next index at or after `from` where `s` holds a character inline must handle, or -1. */
function nextTrigger(s, from) {
  let best = -1;
  for (let t = 0; t < 4; t++) {
    const k = s.indexOf(TRIGGER_CHARS[t], from);
    if (k !== -1 && (best === -1 || k < best)) best = k;
  }
  return best;
}
const TRIGGER_CHARS = ['\\', '`', '*', '['];

/**
 * `s` rendered inline, appended to `out` (an array of string pieces).
 * `env.link(target)` is a link's href. Same rules as the reference: `\` before
 * an escapable character writes that character (escaped); a backtick opens a
 * code span closed by the next backtick with at least one character between;
 * `**` opens strong, a single `*` emphasis; `[text](target)` a link. Every
 * other character is written escaped. Plain runs are sliced whole and escaped
 * in one call; only the trigger characters are handled one by one.
 */
function inlineTo(s, env, out) {
  const n = s.length;
  let run = 0; // start of the current plain run
  let i = nextTrigger(s, 0);
  while (i !== -1) {
    const c = s.charCodeAt(i);
    if (c === 92) {
      if (i + 1 < n && ESCAPABLE[s.charCodeAt(i + 1)] === 1) {
        if (i > run) out.push(escapeHtml(s.slice(run, i)));
        const e = s.charCodeAt(i + 1);
        out.push(ESC[String.fromCharCode(e)] ?? s[i + 1]);
        run = i + 2;
        i = nextTrigger(s, run);
      } else i = nextTrigger(s, i + 1); // a `\` before anything else is itself
      continue;
    }
    if (c === 96) {
      const j = s.indexOf('`', i + 1);
      if (j > i + 1) {
        if (i > run) out.push(escapeHtml(s.slice(run, i)));
        out.push('<code>', escapeHtml(s.slice(i + 1, j)), '</code>');
        run = j + 1;
        i = nextTrigger(s, run);
      } else i = nextTrigger(s, i + 1); // a backtick with no closer is itself
      continue;
    }
    if (c === 42) {
      if (s.charCodeAt(i + 1) === 42) {
        const j = findDoubleStar(s, i + 2);
        if (j > i + 2) {
          if (i > run) out.push(escapeHtml(s.slice(run, i)));
          out.push('<strong>');
          inlineTo(s.slice(i + 2, j), env, out);
          out.push('</strong>');
          run = j + 2;
          i = nextTrigger(s, run);
        } else i = nextTrigger(s, i + 2); // `**` with no closer is itself
        continue;
      }
      const j = findSingleStar(s, i + 1);
      if (j > i + 1) {
        if (i > run) out.push(escapeHtml(s.slice(run, i)));
        out.push('<em>');
        inlineTo(s.slice(i + 1, j), env, out);
        out.push('</em>');
        run = j + 1;
        i = nextTrigger(s, run);
      } else i = nextTrigger(s, i + 1); // a `*` with no closer is itself
      continue;
    }
    // c === 91, a link open
    const k = findUnescapedBracket(s, i + 1);
    const m = k !== -1 && s.charCodeAt(k + 1) === 40 ? s.indexOf(')', k + 2) : -1;
    const target = m === -1 ? '' : s.slice(k + 2, m);
    if (target !== '' && !/\s/.test(target)) {
      if (i > run) out.push(escapeHtml(s.slice(run, i)));
      out.push('<a href="', escapeHtml(env.link(target)), '">');
      inlineTo(s.slice(i + 1, k), env, out);
      out.push('</a>');
      run = m + 1;
      i = nextTrigger(s, run);
    } else i = nextTrigger(s, i + 1); // `[` is itself
  }
  if (n > run) out.push(escapeHtml(s.slice(run, n)));
}

/** `s` rendered inline. */
function inline(s, env) {
  const out = [];
  inlineTo(s, env, out);
  return out.join('');
}

// ---------------------------------------------------------------- markdown: blocks

/** A line trimmed of spaces and tabs at both ends. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return line.slice(a, b);
}

/** Whether `line` is blank (spaces and tabs only). */
function isBlank(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A fence opening line's language, or null: three backticks, an optional language, then spaces or tabs only. */
function fenceOpen(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let i = 3;
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45) i++;
    else break;
  }
  const lang = line.slice(3, i);
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return null;
    i++;
  }
  return lang;
}

/** Whether `line` closes a fence: three backticks, then spaces or tabs only. */
function fenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A heading line's depth and text, or null (a heading's text is never empty; 7 or more # is not a heading). */
function headingOf(line) {
  let n = 0;
  while (n < line.length && line.charCodeAt(n) === 35) n++;
  if (n === 0 || n > 6) return null;
  if (n >= line.length || (line.charCodeAt(n) !== 32 && line.charCodeAt(n) !== 9)) return null;
  const text = trimLine(line.slice(n));
  return text === '' ? null : { depth: n, text };
}

/** Whether `line` is a thematic break: `---` or `***`, then spaces or tabs only. */
function isHr(line) {
  if (line.length < 3) return false;
  const c0 = line.charCodeAt(0);
  const c1 = line.charCodeAt(1);
  const c2 = line.charCodeAt(2);
  if (!((c0 === 45 && c1 === 45 && c2 === 45) || (c0 === 42 && c1 === 42 && c2 === 42))) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  if (line === '') return true;
  const c0 = line.charCodeAt(0);
  if (c0 === 32 || c0 === 9) return isBlank(line);
  if (c0 === 96) return fenceOpen(line) !== null;
  if (c0 === 35) return headingOf(line) !== null;
  if (c0 === 45 || c0 === 42) return isHr(line);
  return false;
}

/** Whether `line` continues a list item: two or more spaces, then a non-space. */
function isContinued(line) {
  let i = 0;
  while (i < line.length && line.charCodeAt(i) === 32) i++;
  return i >= 2 && i < line.length && !isWS(line.charCodeAt(i));
}

/**
 * `src` rendered: its HTML (each block on its own lines, a "\n" after the last), its table of contents (every level 2
 * and 3 heading: level, id and its inline HTML) and its excerpt (the first paragraph's inline HTML, or "").
 * `slugify` is the case's memoized slug function; `env.link(target)` is a link's href.
 */
function renderMarkdown(src, env, slugify) {
  const lines = src.split('\n');
  const ids = new Set();
  const parts = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const lang = fenceOpen(line);
    if (lang !== null) {
      const body = [];
      i++;
      while (i < lines.length && !fenceClose(lines[i])) body.push(lines[i++]);
      i++;
      parts.push(`<pre><code${lang === '' ? '' : ` class="language-${escapeHtml(lang)}"`}>`);
      for (const l of body) {
        parts.push(escapeHtml(l), '\n');
      }
      parts.push('</code></pre>\n');
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const start = parts.length;
      parts.push(`<h${heading.depth} id="${id}">`);
      inlineTo(heading.text, env, parts);
      parts.push(`</h${heading.depth}>\n`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html: parts.slice(start + 1, parts.length - 1).join('') });
      i++;
      continue;
    }
    if (isHr(line)) {
      parts.push('<hr>\n');
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) {
      const body = [];
      while (i < lines.length && lines[i].charCodeAt(0) === 62) {
        let l = lines[i++];
        l = l.slice(1);
        if (l.charCodeAt(0) === 32) l = l.slice(1);
        body.push(l);
      }
      const kept = [];
      for (const l of body) {
        const t = trimLine(l);
        if (t !== '') kept.push(t);
      }
      if (kept.length === 0) parts.push('<blockquote>\n</blockquote>\n');
      else {
        parts.push('<blockquote>\n<p>');
        inlineTo(kept.join('\n'), env, parts);
        parts.push('</p>\n</blockquote>\n');
      }
      continue;
    }
    const c0 = line.charCodeAt(0);
    const c1 = line.length > 1 ? line.charCodeAt(1) : -1;
    let ordered = null;
    let bullet = false;
    if ((c0 === 45 || c0 === 42) && c1 === 32) bullet = true;
    else if (c0 >= 48 && c0 <= 57) {
      let j = 0;
      while (j < line.length && line.charCodeAt(j) >= 48 && line.charCodeAt(j) <= 57) j++;
      if (j >= 1 && j <= 9 && line.charCodeAt(j) === 46 && line.charCodeAt(j + 1) === 32) ordered = { start: Number(line.slice(0, j)), rest: line.slice(j + 2) };
    }
    if (bullet || ordered !== null) {
      const isOrdered = ordered !== null;
      const items = [];
      while (i < lines.length) {
        const l = lines[i];
        let m = null;
        if (isOrdered) {
          let j = 0;
          while (j < l.length && l.charCodeAt(j) >= 48 && l.charCodeAt(j) <= 57) j++;
          if (j >= 1 && j <= 9 && l.charCodeAt(j) === 46 && l.charCodeAt(j + 1) === 32) m = l.slice(j + 2);
        } else if ((l.charCodeAt(0) === 45 || l.charCodeAt(0) === 42) && l.charCodeAt(1) === 32) m = l.slice(2);
        if (m !== null) {
          items.push([trimLine(m)]);
          i++;
        } else if (isContinued(l)) {
          items[items.length - 1].push(trimLine(l));
          i++;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      parts.push(isOrdered && ordered.start !== 1 ? `<ol start="${ordered.start}">\n` : `<${tag}>\n`);
      for (const item of items) {
        parts.push('<li>');
        inlineTo(item.join('\n'), env, parts);
        parts.push('</li>\n');
      }
      parts.push(`</${tag}>\n`);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < lines.length && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const start = parts.length;
    parts.push('<p>');
    inlineTo(body.join('\n'), env, parts);
    parts.push('</p>\n');
    if (excerpt === null) excerpt = parts.slice(start + 1, parts.length - 1).join('');
  }
  return { html: parts.join(''), toc, excerpt: excerpt ?? '' };
}

